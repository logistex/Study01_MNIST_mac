// 학습된 CNN 의 순전파를 자바스크립트로 직접 구현한다.
//
// 이 맥의 파이썬 3.14 에는 onnx 패키지 휠이 없어 ONNX 변환이 불가능하다.
// 다행히 모델이 작아서(파라미터 42만 개, 곱셈덧셈 430만 번) 직접 구현이
// 현실적이다. desktop_version/model.py 의 구조를 그대로 옮긴 것이므로,
// model.py 를 바꾸면 이 파일도 반드시 함께 바꿔야 한다.
//
// 드롭아웃은 예측 모드에서 항등이라 구현하지 않는다.

// 예측하기 가 가정하는 형상. model.py 를 바꾸면 여기도 함께 고쳐야 한다.
const 기대형상표 = {
  "합성곱1.weight": [32, 1, 3, 3], "합성곱1.bias": [32],
  "합성곱2.weight": [64, 32, 3, 3], "합성곱2.bias": [64],
  "전결합1.weight": [128, 3136], "전결합1.bias": [128],
  "전결합2.weight": [10, 128], "전결합2.bias": [10],
};

/** 가중치 바이너리와 형상 정보를 읽어 예측 준비를 마친 모델을 돌려준다. */
export async function 모델불러오기(기준경로 = ".") {
  const 정보응답 = await fetch(`${기준경로}/가중치정보.json`);
  if (!정보응답.ok) {
    throw new Error(`가중치정보.json 을 읽지 못했습니다 (${정보응답.status}).`);
  }
  const 정보 = await 정보응답.json();

  const 바이너리응답 = await fetch(`${기준경로}/가중치.bin`);
  if (!바이너리응답.ok) {
    throw new Error(`가중치.bin 을 읽지 못했습니다 (${바이너리응답.status}).`);
  }
  const 전체 = new Float32Array(await 바이너리응답.arrayBuffer());

  const 가중치 = {};
  let 위치 = 0;
  for (const 텐서 of 정보.텐서) {
    const 개수 = 텐서.형상.reduce((누적, 값) => 누적 * 값, 1);

    // 예측하기 는 층 크기(28, 32, 14, 64, 3136, 128, 10)를 하드코딩해서 쓴다.
    // 여기서 형상을 검사해 두지 않으면, model.py 의 채널 수가 바뀐 뒤
    // 총 원소 수만 우연히 맞아도 예측하기 가 잘못된 경계로 subarray 를 잘라
    // undefined -> NaN 이 번져 무엇을 그려도 "0"이 나오는 조용한 오답이 된다.
    // (전처리.js 의 면적평균축소 NaN 사고와 같은 양식.) 값의 출처는 여전히
    // 가중치정보.json 이고, 이 표는 그 값을 검사만 하는 용도다.
    const 기대형상 = 기대형상표[텐서.이름];
    if (기대형상 === undefined) {
      throw new Error(
        `가중치정보.json 에 알 수 없는 텐서 "${텐서.이름}" 가 있습니다. `
        + `model.py 를 바꿨다면 모델.js 의 기대형상표도 함께 고쳐야 합니다.`
      );
    }
    if (텐서.형상.length !== 기대형상.length
        || 텐서.형상.some((값, 자리) => 값 !== 기대형상[자리])) {
      throw new Error(
        `"${텐서.이름}" 의 형상이 예측하기 가 가정한 것과 다릅니다 `
        + `(실제 [${텐서.형상}], 기대 [${기대형상}]). `
        + `model.py 를 바꿨다면 모델.js 도 함께 고쳐야 합니다.`
      );
    }

    가중치[텐서.이름] = 전체.subarray(위치, 위치 + 개수);
    위치 += 개수;
  }
  if (위치 !== 전체.length) {
    throw new Error(`가중치 크기가 맞지 않습니다 (${위치} / ${전체.length}).`);
  }

  return { 가중치, 평균: 정보.평균, 표준편차: 정보.표준편차 };
}

/** 3x3 합성곱, 패딩 1, 스트라이드 1. 출력 크기는 입력과 같다. */
function 합성곱(입력, 입력채널, 크기, 가중치, 편향, 출력채널) {
  const 출력 = new Float32Array(출력채널 * 크기 * 크기);

  for (let 나감 = 0; 나감 < 출력채널; 나감++) {
    for (let 세로 = 0; 세로 < 크기; 세로++) {
      for (let 가로 = 0; 가로 < 크기; 가로++) {
        let 누적 = 편향[나감];

        for (let 들어옴 = 0; 들어옴 < 입력채널; 들어옴++) {
          const 입력바닥 = 들어옴 * 크기 * 크기;
          const 가중치바닥 = (나감 * 입력채널 + 들어옴) * 9;

          for (let 창세로 = 0; 창세로 < 3; 창세로++) {
            const 원세로 = 세로 + 창세로 - 1;
            if (원세로 < 0 || 원세로 >= 크기) continue;

            for (let 창가로 = 0; 창가로 < 3; 창가로++) {
              const 원가로 = 가로 + 창가로 - 1;
              if (원가로 < 0 || 원가로 >= 크기) continue;

              누적 += 입력[입력바닥 + 원세로 * 크기 + 원가로]
                    * 가중치[가중치바닥 + 창세로 * 3 + 창가로];
            }
          }
        }
        출력[(나감 * 크기 + 세로) * 크기 + 가로] = 누적;
      }
    }
  }
  return 출력;
}

/** 음수를 0으로 만든다. 입력 배열을 그 자리에서 고친다. */
function 렐루(값들) {
  for (let 자리 = 0; 자리 < 값들.length; 자리++) {
    if (값들[자리] < 0) 값들[자리] = 0;
  }
  return 값들;
}

/** 2x2 최댓값 풀링. 크기를 절반으로 줄인다. */
function 맥스풀링2(입력, 채널수, 크기) {
  const 새크기 = Math.floor(크기 / 2);
  const 출력 = new Float32Array(채널수 * 새크기 * 새크기);

  for (let 채널 = 0; 채널 < 채널수; 채널++) {
    const 입력바닥 = 채널 * 크기 * 크기;
    const 출력바닥 = 채널 * 새크기 * 새크기;

    for (let 세로 = 0; 세로 < 새크기; 세로++) {
      for (let 가로 = 0; 가로 < 새크기; 가로++) {
        const 왼위 = 입력바닥 + (세로 * 2) * 크기 + 가로 * 2;
        const 최댓값 = Math.max(
          입력[왼위], 입력[왼위 + 1],
          입력[왼위 + 크기], 입력[왼위 + 크기 + 1],
        );
        출력[출력바닥 + 세로 * 새크기 + 가로] = 최댓값;
      }
    }
  }
  return 출력;
}

/** 완전연결 층. 가중치는 [출력수, 입력수] 형상의 행 우선 배열이다. */
function 전결합(입력, 가중치, 편향, 입력수, 출력수) {
  const 출력 = new Float32Array(출력수);

  for (let 나감 = 0; 나감 < 출력수; 나감++) {
    let 누적 = 편향[나감];
    const 줄시작 = 나감 * 입력수;
    for (let 들어옴 = 0; 들어옴 < 입력수; 들어옴++) {
      누적 += 입력[들어옴] * 가중치[줄시작 + 들어옴];
    }
    출력[나감] = 누적;
  }
  return 출력;
}

/** 점수 10개를 확률로 바꾼다. 큰 값을 빼서 오버플로를 막는다. */
function 소프트맥스(점수) {
  const 최댓값 = Math.max(...점수);
  const 확률 = new Float32Array(점수.length);
  let 합 = 0;
  for (let 자리 = 0; 자리 < 점수.length; 자리++) {
    확률[자리] = Math.exp(점수[자리] - 최댓값);
    합 += 확률[자리];
  }
  for (let 자리 = 0; 자리 < 확률.length; 자리++) {
    확률[자리] /= 합;
  }
  return 확률;
}

/**
 * 정규화를 마친 28x28 입력(Float32Array 784개)을 받아
 * 숫자 0~9 에 대한 확률 10개를 돌려준다.
 */
export function 예측하기(입력, 모델) {
  if (입력.length !== 784) {
    throw new Error(`입력 길이가 784가 아닙니다 (${입력.length}).`);
  }
  const ㄱ = 모델.가중치;

  let 특징 = 합성곱(입력, 1, 28, ㄱ["합성곱1.weight"], ㄱ["합성곱1.bias"], 32);
  특징 = 맥스풀링2(렐루(특징), 32, 28);                       // 32x28x28 -> 32x14x14

  특징 = 합성곱(특징, 32, 14, ㄱ["합성곱2.weight"], ㄱ["합성곱2.bias"], 64);
  특징 = 맥스풀링2(렐루(특징), 64, 14);                       // 64x14x14 -> 64x7x7

  // 평탄화는 별도 작업이 필요 없다. 이미 [채널][세로][가로] 순으로 이어져 있어
  // 파이토치의 flatten 결과와 순서가 같다.
  const 숨은층 = 렐루(전결합(특징, ㄱ["전결합1.weight"], ㄱ["전결합1.bias"], 3136, 128));
  const 점수 = 전결합(숨은층, ㄱ["전결합2.weight"], ㄱ["전결합2.bias"], 128, 10);

  return 소프트맥스(점수);
}
