// 캔버스에 그린 그림을 MNIST 형식으로 바꾸는 전처리.
// desktop_version/preprocess.py 를 자바스크립트로 옮긴 것이다.
//
// MNIST 이미지는 단순히 28x28 로 줄인 그림이 아니라 다음 규칙으로 만들어졌다.
//   1. 숫자가 없는 바깥 여백을 잘라낸다.
//   2. 가로세로 비율을 유지한 채 20x20 안에 들어가도록 줄인다.
//   3. 28x28 검은 배경 위에, 숫자의 무게중심이 한가운데에 오도록 붙인다.
// 셋 중 하나라도 빠지면 인식률이 뚝 떨어진다.
//
// 파이썬과 딱 한 곳이 다르다. PIL 의 LANCZOS 축소를 브라우저에서 똑같이
// 재현할 수 없어 면적 평균 축소를 직접 구현했다. 이 차이가 정확도에 영향을
// 주는지는 검증.html 로 판정한다.

/** 파이썬 round 와 같은 규칙(정확히 0.5 면 짝수 쪽)으로 반올림한다. */
function 파이썬반올림(값) {
  const 내림 = Math.floor(값);
  const 나머지 = 값 - 내림;
  if (나머지 > 0.5) return 내림 + 1;
  if (나머지 < 0.5) return 내림;
  return 내림 % 2 === 0 ? 내림 : 내림 + 1;
}

/**
 * Canvas 2D 의 ImageData 에서 밝기만 뽑는다.
 *
 * 캔버스에는 검은 배경에 흰 글씨만 그리므로 R, G, B 가 항상 같다.
 * 그래서 R 채널을 그대로 밝기로 쓴다.
 */
export function 밝기만뽑기(이미지자료) {
  const 화소수 = 이미지자료.width * 이미지자료.height;
  const 밝기 = new Float32Array(화소수);
  for (let 자리 = 0; 자리 < 화소수; 자리++) {
    밝기[자리] = 이미지자료.data[자리 * 4];
  }
  return 밝기;
}

/** 면적 평균으로 축소한다. 겹치는 넓이를 가중치로 삼는다. */
function 면적평균축소(밝기, 너비, 높이, 새너비, 새높이) {
  const 출력 = new Float32Array(새너비 * 새높이);
  const 가로비 = 너비 / 새너비;
  const 세로비 = 높이 / 새높이;

  for (let 새세로 = 0; 새세로 < 새높이; 새세로++) {
    const 위 = 새세로 * 세로비;
    const 아래 = (새세로 + 1) * 세로비;

    for (let 새가로 = 0; 새가로 < 새너비; 새가로++) {
      const 왼 = 새가로 * 가로비;
      const 오른 = (새가로 + 1) * 가로비;

      let 누적 = 0;
      let 넓이합 = 0;

      for (let 세로 = Math.floor(위); 세로 < Math.min(높이, Math.ceil(아래)); 세로++) {
        const 세로겹침 = Math.min(아래, 세로 + 1) - Math.max(위, 세로);
        if (세로겹침 <= 0) continue;

        for (let 가로 = Math.floor(왼); 가로 < Math.min(너비, Math.ceil(오른)); 가로++) {
          const 가로겹침 = Math.min(오른, 가로 + 1) - Math.max(왼, 가로);
          if (가로겹침 <= 0) continue;

          const 넓이 = 세로겹침 * 가로겹침;
          누적 += 밝기[세로 * 너비 + 가로] * 넓이;
          넓이합 += 넓이;
        }
      }
      출력[새세로 * 새너비 + 새가로] = 넓이합 > 0 ? 누적 / 넓이합 : 0;
    }
  }
  return 출력;
}

/**
 * 검은 배경에 흰 글씨로 그린 밝기 배열을 28x28 MNIST 형식으로 바꾼다.
 * 결과는 밝기 0~255 값을 담은 Float32Array(784) 이고,
 * 아무것도 그리지 않았으면 null 을 돌려준다.
 */
export function mnist형식으로변환(밝기, 너비, 높이) {
  // 1) 글씨가 있는 부분(밝은 화소)의 최소 사각형을 찾는다.
  let 윗줄 = 높이, 아랫줄 = -1, 왼쪽 = 너비, 오른쪽 = -1;
  for (let 세로 = 0; 세로 < 높이; 세로++) {
    for (let 가로 = 0; 가로 < 너비; 가로++) {
      if (밝기[세로 * 너비 + 가로] > 20) {
        if (세로 < 윗줄) 윗줄 = 세로;
        if (세로 > 아랫줄) 아랫줄 = 세로;
        if (가로 < 왼쪽) 왼쪽 = 가로;
        if (가로 > 오른쪽) 오른쪽 = 가로;
      }
    }
  }
  if (아랫줄 < 0) return null;

  const 자른너비 = 오른쪽 - 왼쪽 + 1;
  const 자른높이 = 아랫줄 - 윗줄 + 1;
  const 자른것 = new Float32Array(자른너비 * 자른높이);
  for (let 세로 = 0; 세로 < 자른높이; 세로++) {
    for (let 가로 = 0; 가로 < 자른너비; 가로++) {
      자른것[세로 * 자른너비 + 가로] = 밝기[(윗줄 + 세로) * 너비 + (왼쪽 + 가로)];
    }
  }

  // 2) 비율을 유지하며 긴 변이 20이 되도록 줄인다.
  const 비율 = 20.0 / Math.max(자른너비, 자른높이);
  const 새너비 = Math.max(1, 파이썬반올림(자른너비 * 비율));
  const 새높이 = Math.max(1, 파이썬반올림(자른높이 * 비율));
  const 줄인것 = 면적평균축소(자른것, 자른너비, 자른높이, 새너비, 새높이);

  // 3) 28x28 검은 배경 한가운데에 일단 붙인다.
  const 도화지 = new Float32Array(28 * 28);
  const 붙일가로 = Math.floor((28 - 새너비) / 2);
  const 붙일세로 = Math.floor((28 - 새높이) / 2);
  for (let 세로 = 0; 세로 < 새높이; 세로++) {
    for (let 가로 = 0; 가로 < 새너비; 가로++) {
      도화지[(붙일세로 + 세로) * 28 + (붙일가로 + 가로)] = 줄인것[세로 * 새너비 + 가로];
    }
  }

  // 4) 밝기를 무게로 삼아 무게중심을 계산하고, 중앙(13.5, 13.5)으로 옮긴다.
  let 전체무게 = 0;
  let 세로가중합 = 0;
  let 가로가중합 = 0;
  for (let 세로 = 0; 세로 < 28; 세로++) {
    for (let 가로 = 0; 가로 < 28; 가로++) {
      const 무게 = 도화지[세로 * 28 + 가로];
      전체무게 += 무게;
      세로가중합 += 세로 * 무게;
      가로가중합 += 가로 * 무게;
    }
  }
  if (전체무게 <= 0) return 도화지;

  const 옮길가로 = 파이썬반올림(13.5 - 가로가중합 / 전체무게);
  const 옮길세로 = 파이썬반올림(13.5 - 세로가중합 / 전체무게);
  if (옮길가로 === 0 && 옮길세로 === 0) return 도화지;

  const 옮긴것 = new Float32Array(28 * 28);
  for (let 세로 = 0; 세로 < 28; 세로++) {
    const 원세로 = 세로 - 옮길세로;
    if (원세로 < 0 || 원세로 >= 28) continue;
    for (let 가로 = 0; 가로 < 28; 가로++) {
      const 원가로 = 가로 - 옮길가로;
      if (원가로 < 0 || 원가로 >= 28) continue;
      옮긴것[세로 * 28 + 가로] = 도화지[원세로 * 28 + 원가로];
    }
  }
  return 옮긴것;
}

/** 학습 때 쓴 값으로 정규화해 모델 입력 형태로 만든다. */
export function 정규화(밝기, 평균, 표준편차) {
  const 입력 = new Float32Array(밝기.length);
  for (let 자리 = 0; 자리 < 밝기.length; 자리++) {
    입력[자리] = (밝기[자리] / 255 - 평균) / 표준편차;
  }
  return 입력;
}
