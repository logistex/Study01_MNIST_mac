"""캔버스에 그린 그림을 MNIST 형식으로 바꾸는 전처리.

MNIST 이미지는 단순히 28x28로 줄인 그림이 아니라, 다음 규칙으로 만들어졌다.

1. 숫자가 없는 바깥 여백을 잘라낸다.
2. 가로세로 비율을 유지한 채 20x20 안에 들어가도록 크기를 줄인다.
3. 28x28 검은 배경 위에, 숫자의 무게중심이 한가운데에 오도록 붙인다.

같은 규칙으로 맞춰 주지 않으면 학습 때와 그림 모양이 달라져 인식률이 뚝 떨어진다.
"""

import numpy as np
from PIL import Image

# 학습할 때 쓴 정규화 값 (MNIST 전체의 평균과 표준편차)
평균 = 0.1307
표준편차 = 0.3081


def mnist형식으로변환(그림: Image.Image) -> Image.Image | None:
    """검은 배경에 흰 글씨로 그린 그림을 28x28 MNIST 형식으로 바꾼다.

    아무것도 그리지 않았으면 None을 돌려준다.
    """
    흑백 = 그림.convert("L")
    화소 = np.array(흑백)

    # 1) 글씨가 있는 부분(밝은 화소)의 최소 사각형을 찾는다.
    글씨위치 = 화소 > 20
    if not 글씨위치.any():
        return None

    행있음 = np.where(글씨위치.any(axis=1))[0]
    열있음 = np.where(글씨위치.any(axis=0))[0]
    윗줄, 아랫줄 = 행있음[0], 행있음[-1]
    왼쪽, 오른쪽 = 열있음[0], 열있음[-1]
    잘라낸그림 = 흑백.crop((왼쪽, 윗줄, 오른쪽 + 1, 아랫줄 + 1))

    # 2) 비율을 유지하며 긴 변이 20이 되도록 줄인다.
    너비, 높이 = 잘라낸그림.size
    비율 = 20.0 / max(너비, 높이)
    새너비 = max(1, round(너비 * 비율))
    새높이 = max(1, round(높이 * 비율))
    줄인그림 = 잘라낸그림.resize((새너비, 새높이), Image.LANCZOS)

    # 3) 28x28 검은 배경 한가운데에 일단 붙인다.
    도화지 = Image.new("L", (28, 28), 0)
    도화지.paste(줄인그림, ((28 - 새너비) // 2, (28 - 새높이) // 2))

    # 4) 밝기를 무게로 삼아 무게중심을 계산하고, 중앙(13.5, 13.5)으로 옮긴다.
    최종화소 = np.array(도화지, dtype=np.float32)
    전체무게 = 최종화소.sum()
    if 전체무게 > 0:
        세로좌표, 가로좌표 = np.indices(최종화소.shape)
        무게중심y = (세로좌표 * 최종화소).sum() / 전체무게
        무게중심x = (가로좌표 * 최종화소).sum() / 전체무게
        옮길x = round(13.5 - 무게중심x)
        옮길y = round(13.5 - 무게중심y)
        도화지 = 도화지.transform(
            (28, 28), Image.AFFINE, (1, 0, -옮길x, 0, 1, -옮길y), fillcolor=0
        )

    return 도화지


def 텐서로변환(이미지: Image.Image):
    """28x28 이미지를 모델 입력용 텐서(1, 1, 28, 28)로 바꾼다."""
    import torch

    화소 = np.array(이미지, dtype=np.float32) / 255.0
    화소 = (화소 - 평균) / 표준편차
    return torch.from_numpy(화소).unsqueeze(0).unsqueeze(0)
